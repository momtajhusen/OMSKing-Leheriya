const { paymentStanding, invoiceNumber } = require('../services/finance.service');

const SLA_CHANNELS = ['Amazon', 'Myntra'];

function slaDateOf(order) {
  if (!SLA_CHANNELS.includes(order.channel)) return null;
  const dates = (order.channelLines || []).map((line) => line.shipByTime).filter(Boolean).map((d) => new Date(d));
  return dates.length ? new Date(Math.min(...dates)) : null;
}

function toOrderDto(doc) {
  const order = typeof doc.toObject === 'function' ? doc.toObject() : doc;
  const subOrders = order.subOrders || [];
  return {
    id: order.orderNo,
    orderNo: order.orderNo,
    channelOrderNo: order.channelOrderNo || (order.channel === 'Shopify' ? '' : order.externalOrderId || ''),
    customer: order.customer,
    email: order.email,
    phone: order.phone,
    address: order.address,
    city: order.city,
    customerGstin: order.customerGstin || '',
    notes: order.notes || '',
    channel: order.channel,
    warehouseCode: order.warehouseCode || '',
    status: order.status,
    paymentMode: order.paymentMode,
    labelPaymentMode: order.labelPaymentMode || '',
    paymentStatus: order.paymentStatus || '',
    paymentLabel: paymentStanding(order).label,
    paid: paymentStanding(order).paid,
    shipState: order.shipState || '',
    fulfilmentSource: order.fulfilmentSource,
    assignedVendor: order.assignedVendor || '',
    shopifyVendor: order.shopifyVendor || '',
    items: (order.items || []).map((item) => ({
      name: item.name,
      sku: item.sku,
      qty: item.qty,
      price: item.price,
      cost: item.cost,
      hsn: item.hsn,
      gst: item.gst,
      imageUrl: item.imageUrl,
      vendor: item.vendor || '',
      masterSkuId: item.masterSkuId ? String(item.masterSkuId) : '',
      fulfilmentSource: item.fulfilmentSource || order.fulfilmentSource || 'Offline',
      pack: item.pack || null,
    })),
    subOrders: subOrders.map((sub) => ({
      id: sub.id,
      index: sub.index,
      sku: sub.sku,
      title: sub.title,
      imageUrl: sub.imageUrl,
      qty: sub.qty,
      price: sub.price,
      assignedVendor: sub.assignedVendor,
      vendorPhone: sub.vendorPhone,
      vendorEmail: sub.vendorEmail,
      vendorLocation: sub.vendorLocation,
      assignedDate: sub.assignedDate,
      dispatchDate: sub.dispatchDate,
      deliveryStatus: sub.deliveryStatus,
      status: sub.status,
      address: sub.address,
      customer: sub.customer,
      fulfilmentSource: sub.fulfilmentSource || order.fulfilmentSource || 'Offline',
      vendorStatus: sub.vendorStatus || (sub.assignedVendor ? 'Pending Acceptance' : ''),
      rejectReason: sub.rejectReason || '',
      trackingNumber: sub.trackingNumber || '',
      courier: sub.courier || '',
      deliveredDate: sub.deliveredDate || '',
    })),
    subOrderIndexMap: Object.fromEntries(subOrders.map((sub) => [String(sub.index), sub.id])),
    total: order.total,
    createdAt: order.orderDate || order.createdAt,
    courier: order.courier || '',
    awb: order.awb || '',
    invoiceNo: order.channel === 'Shopify' ? invoiceNumber(order) : (order.invoiceNo || ''),
    labelGeneratedAt: order.labelGeneratedAt || null,
    handoverAt: order.handoverAt || null,
    manifestNo: order.manifestNo || '',
    pickedUpAt: order.pickedUpAt || null,
    easyShip: order.easyShip?.packageId ? {
      packageId: order.easyShip.packageId,
      status: order.easyShip.status || '',
      slotStart: order.easyShip.slotStart || null,
      slotEnd: order.easyShip.slotEnd || null,
      handover: order.easyShip.handover || '',
    } : null,
    invoiceGeneratedAt: order.invoiceGeneratedAt || null,
    reversePickup: order.reversePickup || null,
    source: order.source || 'demo',
    externalOrderId: order.externalOrderId || '',
    channelStatus: order.channelStatus || '',
    channelLines: (order.channelLines || []).map((line) => ({
      sellerOrderId: line.sellerOrderId,
      orderLineId: line.orderLineId,
      sku: line.sku,
      imageUrl: line.imageUrl || '',
      status: line.status,
      packetId: line.packetId || '',
      invoiceNumber: line.invoiceNumber || '',
      trackingNumber: line.trackingNumber || '',
      courierCode: line.courierCode || '',
      cancellationReason: line.cancellationReason || '',
      packByTime: line.packByTime || null,
      shipByTime: line.shipByTime || null,
    })),
    lastChannelSyncAt: order.lastChannelSyncAt || null,
    slaDate: slaDateOf(order),
  };
}

module.exports = { toOrderDto };
